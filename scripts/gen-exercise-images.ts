import fs from 'fs';
import path from 'path';
import { EXERCISES } from '../src/data/exercises';

const VALID_EXTENSIONS = new Set(['.jpg', '.jpeg', '.png', '.webp']);
const ROOT_DIR = path.resolve(__dirname, '..');
const ASSETS_DIR = path.join(ROOT_DIR, 'assets', 'exercises');
const OUTPUT_FILE = path.join(ROOT_DIR, 'src', 'data', 'exerciseImages.ts');

export function runGenExerciseImages(): void {
  if (!fs.existsSync(ASSETS_DIR)) {
    fs.mkdirSync(ASSETS_DIR, { recursive: true });
  }

  const catalogIds = new Set(EXERCISES.map((ex) => ex.id));
  const entries = fs
    .readdirSync(ASSETS_DIR, { withFileTypes: true })
    .filter((entry) => entry.isFile())
    .map((entry) => entry.name)
    .filter((name) => VALID_EXTENSIONS.has(path.extname(name).toLowerCase()))
    .sort((a, b) => a.localeCompare(b));

  const matched = new Map<string, string>();
  const unmatchedFiles: string[] = [];

  for (const fileName of entries) {
    const ext = path.extname(fileName);
    const id = path.basename(fileName, ext);
    if (!catalogIds.has(id)) {
      unmatchedFiles.push(fileName);
    }
    if (!matched.has(id)) {
      matched.set(id, fileName);
    }
  }

  const lines: string[] = [
    "import type { ImageSourcePropType } from 'react-native';",
    '',
    '// Auto-generated by `npm run gen:images`. Do not edit manually.',
    'export const EXERCISE_IMAGES: Record<string, ImageSourcePropType> = {',
  ];

  for (const [id, fileName] of matched.entries()) {
    lines.push(`  '${id}': require('../../assets/exercises/${fileName}'),`);
  }

  lines.push('};', '');

  fs.writeFileSync(OUTPUT_FILE, lines.join('\n'), 'utf8');

  console.log(
    `Generated src/data/exerciseImages.ts with ${matched.size} image(s).`
  );

  if (unmatchedFiles.length > 0) {
    console.warn(
      `\nWarning: ${unmatchedFiles.length} file(s) do not match any catalog exercise id:`
    );
    for (const f of unmatchedFiles) {
      console.warn(`  - ${f}`);
    }
  }

  const missingIds = EXERCISES.filter((ex) => !matched.has(ex.id)).map(
    (ex) => ex.id
  );
  console.log(
    `\nCatalog exercises missing an image (${missingIds.length}/${EXERCISES.length}):`
  );
  for (const id of missingIds) {
    console.log(`  - ${id}`);
  }
}

if (require.main === module) {
  runGenExerciseImages();
}
